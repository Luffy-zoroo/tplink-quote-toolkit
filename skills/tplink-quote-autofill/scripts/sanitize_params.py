"""
品牌词中性化（控标参数脱品牌处理）

投标控标参数不得出现自家品牌名或自有平台/APP 名称——否则等于指定品牌，
容易被判定为排他性条款。本模块把常见的品牌性字眼替换为中性行业通用表述。

用法：
    from sanitize_params import sanitize_text, sanitize_multiline, scan_text, RULES
    clean = sanitize_multiline(raw)          # 直接清洗
    hits  = scan_text(raw)                   # 只检测不替换，返回命中列表

设计原则：
  1) 只替换"品牌指向性"字眼，不动技术指标（数字、速率、接口、协议、温度…）。
  2) 长词优先匹配，避免"TP-LINK商云"被"商云"先吃掉留下"TP-LINK"。
  3) 替换后统一整理标点/空格，但不改变分条编号（1、2、★1、▲1 等）。
"""

