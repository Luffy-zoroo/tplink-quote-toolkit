# 品牌/平台名黑名单（用于检测与校验，不做替换时也能告警）
# ⚠️ 2026-09-24 修：移除 '商用云平台'。它已是中性词（也是 TP-LINK商用云平台 的
#    替换产物），留在黑名单里会把合规文本误报为残留。
BRAND_WORDS = [
    '商云', 'TP-LINK', 'Tp-Link', 'tp-link', 'TP-LINK商云',
    'TUMS', 'tums', '图门', '算法商城', '算法超市', 'TP-SRC', 'SRC码控',
    '海康', '大华', '宇视',
]


def sanitize_text(text: str) -> str:
    """对单条参数文本做品牌词中性化。

    目标标准（2026-09-24 用户明确）：**捕捉品牌倾向 → 保留原意 → 读得通顺**。
    不追求机械替换，替换后整句必须仍然通顺、语义不丢。
    """
    if not text:
        return text
    s = str(text)
    for old, new in RULES:
        if old and old in s:
            s = s.replace(old, new)

    # ---- 清理替换后产生的冗余，目标是"读得通顺" ----
    # 品牌词删空/替换后容易余下孤立的助词、连接词、标点，逐类收掉
    # 0) 先收「品牌词+的」留下的孤立「的」——必须在替换后、其他清理前做
    #    例：'TP-LINK的智能码控算法' → '的智能码控算法'（TP-LINK 被删空）
    #    例：'支持TP-LINK的智能码控算法' → '支持的智能码控算法'（品牌词在中间）
    #    判断依据：该「的」前面是标点/空格/行首，或前面紧邻的词已因替换消失
    s = re.sub(r'^[\s、，。；：]*的(?=[\w\u4e00-\u9fa5])', '', s)      # 行首（含标点后）孤立「的」
    s = re.sub(r'([、，。；：\s])的(?=[\w\u4e00-\u9fa5])', r'\1', s)   # 标点/空格后孤立「的」
    # 品牌词被整段删除后，前一个汉字与「的」直接相邻的情况：
    # 若「XX的」中 XX 是一个动词短语残尾（如 支持/具备/采用/内置/包含 等 + 的），
    # 这些是常见搭配，正常保留；但品牌词删空会制造出「汉字X+的」的假连接，
    # 用「动词+的+名词」的白名单无法穷举，改为：只在「的」后紧跟技术名词且
    # 前词是「支持/具备/采用/集成/内置/兼容/通过/基于」时，把「的」收掉。
    s = re.sub(r'(支持|具备|采用|集成|内置|兼容|通过|基于|提供|实现|可)的(?=[\u4e00-\u9fa5A-Za-z])', r'\1', s)
    # 1) 竞品名被替换后会产生重复的「主流品牌」，统一合并为一个
    s = re.sub(r'主流品牌(\s*[、,，/和及与等]\s*主流品牌)+', '主流品牌', s)
    s = re.sub(r'主流品牌(\s*主流品牌)+', '主流品牌', s)
    # 1x) 「主流品牌等主流品牌」这种夹着「等」的也要收
    s = re.sub(r'主流品牌(等|、|,|，)*主流品牌', '主流品牌', s)
    # 2) 叠词去重：如「智能码控算法算法」「商用网络平台平台」
    s = re.sub(r'([\u4e00-\u9fa5]{2,6})\1', r'\1', s)
    # 4) 空白与标点整理
    s = re.sub(r'[ \t]{2,}', ' ', s)              # 多空格合一
    s = re.sub(r'（\s*）|\(\s*\)', '', s)          # 空括号
    s = re.sub(r'、\s*、', '、', s)                # 连续顿号
    s = re.sub(r'，\s*，', '，', s)                # 连续逗号
    s = re.sub(r'^[、,，;；\s]+', '', s)           # 行首多余标点
    # ⚠️ 2026-09-24 修：行尾**只清「、」「,」**，绝不碰「；」「。」。
    #    实测回归事故：原实现 `[、,，;；]\s*$` 把分条末尾的「；」「。」也吃了，
    #    '检测更稳定；' → '检测更稳定'，控标分条的断句结构被破坏（读起来不通顺）。
    #    分号/句号在参数分条里是正常且必要的标点。
    s = re.sub(r'[、,，]\s*$', '', s)              # 行尾多余标点（不含；。）
    s = re.sub(r'\s+([、，。；：])', r'\1', s)     # 标点前空格
    s = re.sub(r'([（])\s+', r'\1', s)             # 左括号后空格
    return s.strip()


def sanitize_multiline(text: str) -> str:
    """按行清洗（保持分条结构与编号不变）。"""
    if not text:
        return text
    return '\n'.join(sanitize_text(ln) for ln in str(text).split('\n'))


def scan_text(text: str):
    """只检测不替换。返回 [(命中词, 该行文本片段)]。"""
    hits = []
    if not text:
        return hits
    for ln in str(text).split('\n'):
        for w in BRAND_WORDS:
            if w and w in ln:
                hits.append((w, ln.strip()[:160]))
                break
    return hits


